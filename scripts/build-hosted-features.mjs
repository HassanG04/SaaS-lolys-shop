import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = new URL('../', import.meta.url)
const read = (path) => readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n')
const migration = (name) => read(`supabase/migrations/${name}.sql`)
const digest = (text) => createHash('md5').update(text).digest('hex')

export function section(source, start, end) {
  const from = source.indexOf(start)
  const to = end ? source.indexOf(end, from + start.length) : source.length
  assert(from >= 0 && to > from, `Missing SQL section: ${start}`)
  return source.slice(from, to).trim() + '\n'
}

function functionSql(source, name) {
  return section(source, `create or replace function public.${name}(`, '\n$$;') + '$$;\n'
}

function knownFunctionGuard(name, signature) {
  const hashes = new Set()
  for (const file of readdirSync(new URL('supabase/migrations/', root))) {
    if (!file.endsWith('.sql')) continue
    const source = read(`supabase/migrations/${file}`)
    if (!source.includes(`create or replace function public.${name}(`)) continue
    const sql = functionSql(source, name)
    // prosrc preserves the newlines inside the dollar-quoted function body.
    const body = sql.slice(sql.indexOf('as $$') + 5, sql.lastIndexOf('$$;'))
    hashes.add(digest(body))
  }
  assert(hashes.size > 0)
  return `do $known_function$
begin
  if not exists (select 1 from pg_proc where oid = to_regprocedure('${signature}')
    and proowner = 'postgres'::regrole and prosecdef
    and proconfig = array['search_path=public']
    and md5(replace(prosrc, chr(13), '')) in (${[...hashes].map((h) => `'${h}'`).join(', ')})) then
    raise exception 'Unrecognized ${name}. Stop and share the error; do not bypass this check';
  end if;
end;
$known_function$;\n`
}

export function buildHostedFeatures() {
  const postal = migration('20261018090000_postal_legacy_update_guards')
  const notifications = migration('20261018140000_customer_notifications_and_suggestions')
  const avatar = migration('20261018160000_customer_profile_photo')
  const occasions = migration('20261018180000_occasion_reminders')
  const settings = migration('20261018200000_instapay_themed_qr')
  const parts = [
    '-- Lolys hosted feature repair, 2026-10-29. OWNER-RUN, not a fresh database setup.\n' +
      '-- Run the ENTIRE file as postgres in Supabase SQL Editor. No selection.\n' +
      '-- Generated by node scripts/build-hosted-features.mjs; do not edit guards.\n' +
      '-- BEGIN/COMMIT is atomic: a failed check cancels this repair.\n' +
      "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '120s';\n" +
      'set local search_path = public, extensions;\n',
    read('docs/runbooks/hosted-features/preflight.sql'),
    knownFunctionGuard('admin_anonymize_customer', 'public.admin_anonymize_customer(uuid)'),
    knownFunctionGuard('admin_update_setting', 'public.admin_update_setting(text,jsonb)'),
    section(postal, '-- T-4.08b:', '-- Restore the v2'),
    section(
      notifications,
      '-- 1. Customer Notifications Table',
      '-- 7. Update Customer Anonymization',
    ),
    section(avatar, '-- 1. Add avatar_url', '-- 9. Update admin_anonymize_customer'),
    section(occasions, '-- 1. Storage protect_delete', '-- 3. Update admin_update_setting'),
    section(occasions, '-- 4. Create admin_occasion_reminders'),
    // Use the latest settings validator, keeping InstaPay link support. Never replace
    // get_payment_instructions, place_order or the separate storefront editor RPC.
    functionSql(settings, 'admin_update_setting'),
    'revoke all on function public.admin_update_setting(text,jsonb) from public, anon;\n' +
      'grant execute on function public.admin_update_setting(text,jsonb) to authenticated;\n',
    read('docs/runbooks/hosted-features/forecast-export.sql'),
    read('docs/runbooks/hosted-features/permissions.sql'),
    read('docs/runbooks/hosted-features/postflight.sql'),
    "notify pgrst, 'reload schema';\ncommit;\n",
    read('docs/runbooks/hosted-features-CHECK.sql'),
  ]
  return parts.map((part) => part.trim()).join('\n\n') + '\n'
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const path = new URL('docs/runbooks/hosted-features-APPLY.sql', root)
  writeFileSync(path, buildHostedFeatures())
  console.log(`Wrote ${fileURLToPath(path)}`)
}
