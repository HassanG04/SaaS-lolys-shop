import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
export const repairSources = [
  '20261018090000_postal_legacy_update_guards.sql',
  '20261018100000_storefront_content.sql',
  '20261018140000_customer_notifications_and_suggestions.sql',
  '20261018160000_customer_profile_photo.sql',
  '20261018170000_instapay_recipient_and_qr.sql',
  '20261018180000_occasion_reminders.sql',
  '20261018200000_instapay_themed_qr.sql',
  '20261026100000_explicit_api_schema_permissions.sql',
]
const read = (file) => readFileSync(path.join(root, file), 'utf8').replace(/\r/g, '')

export function buildHostedRepair() {
  const postal = read(
    'supabase/migrations/20261017120000_required_postal_code_and_address_snapshot.sql',
  )
  const start = postal.indexOf('create or replace function public.place_order(')
  const end = postal.indexOf('\n$$;', start)
  if (start < 0 || end < start) throw new Error('Cannot locate the reviewed checkout function')
  const checkout = postal.slice(start, end + 4)
  const pieces = repairSources.map(
    (name) => `-- SOURCE: ${name}\n${read(`supabase/migrations/${name}`)}`,
  )
  return `-- GENERATED by scripts/build-hosted-repair.mjs; do not hand-edit.
-- Target: audited Lolys hosted schema, 2026-10-26; not a general initializer.
-- Owner only. Read hosted-repair-2026-10-26.md, back up, and review before use.
-- DEFAULT IS A REHEARSAL: the final ROLLBACK discards all changes.
-- Never run selected statements; execute the entire file in one session.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';
set local search_path = public, extensions;
select pg_advisory_xact_lock(261026, 206);
${read('docs/runbooks/hosted-repair-preflight.sql')}
-- Lock before taking the snapshot; failures leave the original schema intact.
lock table public.profiles, public.orders, public.products, public.order_items,
  public.shop_settings, public.delivery_fees in share row exclusive mode;
create temporary table lolys_preserved_settings on commit drop as
  select key, value, is_public from public.shop_settings;

-- Restore the exact main definition (the hosted difference is comments only).
${checkout}

${pieces.join('\n\n')}

-- Refuse to commit if the repair overwrote unrelated merchant settings.
do $preserve$
begin
  if exists (
    select 1 from lolys_preserved_settings before
    left join public.shop_settings after using (key)
    where after.key is null or (
      before.key <> 'instapay_handle' and before.value is distinct from after.value
    ) or (
      before.key = 'instapay_handle'
      and before.value is distinct from after.value
      and not (before.value is null or before.value in ('null'::jsonb, '""'::jsonb))
    ) or before.is_public is distinct from after.is_public
  ) then raise exception 'Recovery changed an existing merchant setting; transaction aborted'; end if;
end;
$preserve$;
notify pgrst, 'reload schema';
select 'Repair statements passed. The final ROLLBACK or COMMIT determines whether changes are saved.' as result;
rollback;
`
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const output = path.join(root, 'docs/runbooks/hosted-repair-2026-10-26.sql')
  const sql = buildHostedRepair()
  if (process.argv[2] === '--check') {
    if (readFileSync(output, 'utf8').replace(/\r/g, '') !== sql)
      throw new Error('Regenerate hosted repair SQL')
    console.log('Hosted repair SQL matches reviewed sources.')
  } else if (process.argv.length === 2) {
    writeFileSync(output, sql)
    console.log('Generated owner-review repair SQL with ROLLBACK by default.')
  } else throw new Error('Expected no arguments or --check')
}
